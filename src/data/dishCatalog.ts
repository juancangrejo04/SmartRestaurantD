/**
 * Returns dishes for a specific country from the catalog
 */
export function getDishesForCountry(country: CountryCode): CatalogDish[] {
  return DISH_CATALOG.filter((d) => d.country === country);
}

/**
 * Helper to build MenuItems for a restaurant & branch based on the country
 */
export function buildMenuItemsForBranch(restaurantId: string, branchId: string, country: CountryCode): MenuItem[] {
  const countryDishes = getDishesForCountry(country);
  return countryDishes.map((dish, idx) => ({
    id: `${branchId}-${dish.id}`,
    restaurantId,
    branchId,
    country,
    name: dish.name,
    description: dish.description,
    category: dish.category,
    price: dish.price,
    basePriceUSD: dish.basePriceUSD,
    prepTimeMinutes: dish.prepTimeMinutes,
    available: true,
    image: dish.image,
    emoji: dish.emoji,
    gradient: dish.gradient,
    dietary: dish.dietary,
    popular: dish.popular,
  }));
}
